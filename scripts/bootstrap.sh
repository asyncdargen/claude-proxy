#!/usr/bin/env bash
# One-shot quick start from the prebuilt images: fetch the compose file, write a .env with
# random secrets, start the stack.
#
#   curl -fsSL https://raw.githubusercontent.com/asyncdargen/claude-proxy/master/scripts/bootstrap.sh | bash
#   scripts/bootstrap.sh [--allinone] [--dir ./claude-proxy] [--port 8080] [--no-start]
#
# An existing .env is never overwritten — rerunning only refreshes the compose file and restarts.
# Environment: CLAUDE_PROXY_TAG (image tag, default latest), CLAUDE_PROXY_REF (git ref the compose
# file is fetched from, default master), CLAUDE_PROXY_RAW (base URL override, e.g. file://…).
set -euo pipefail

dir="./claude-proxy"
variant=split
port=8080
start=1
while [ $# -gt 0 ]; do
    case "$1" in
        --allinone) variant=allinone ;;
        --dir) dir="$2"; shift ;;
        --port) port="$2"; shift ;;
        --no-start) start=0 ;;
        -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

raw="${CLAUDE_PROXY_RAW:-https://raw.githubusercontent.com/asyncdargen/claude-proxy/${CLAUDE_PROXY_REF:-master}/deploy/compose}"
compose_file=docker-compose.yml
[ "$variant" = allinone ] && compose_file=docker-compose.allinone.yml

command -v docker >/dev/null || { echo "docker is required" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "the docker compose plugin (v2) is required" >&2; exit 1; }

secret() {
    if command -v openssl >/dev/null; then openssl rand -hex 32
    else head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; fi
}

mkdir -p "$dir"
cd "$dir"
echo "==> fetching $compose_file into $(pwd)"
curl -fsSL "$raw/$compose_file" -o "$compose_file"

if [ -f .env ]; then
    echo "==> keeping the existing .env"
else
    admin_password="$(secret | cut -c1-20)"
    umask 077
    cat > .env <<EOF
# Generated by claude-proxy bootstrap on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private:
# MASTER_KEY decrypts every stored account — back it up, losing it loses the accounts.
MASTER_KEY=$(secret)
SESSION_SECRET=$(secret)
ADMIN_USER=admin
ADMIN_PASSWORD=$admin_password
DATABASE_PASSWORD=$(secret)
INTERNAL_TOKEN=$(secret)
HTTP_PORT=$port
CLAUDE_PROXY_TAG=${CLAUDE_PROXY_TAG:-latest}
# PUBLIC_DOMAIN=proxy.example.com
# HTTP_BIND=0.0.0.0
EOF
    echo "==> wrote .env with random secrets"
    echo "    admin login: admin / $admin_password   (change it after the first sign-in)"
fi

if [ "$start" = 1 ]; then
    echo "==> starting"
    docker compose -f "$compose_file" up -d
    echo "==> open http://127.0.0.1:$(sed -n 's/^HTTP_PORT=//p' .env | tail -n1 | grep . || echo 8080)"
else
    echo "==> start it with: cd $(pwd) && docker compose -f $compose_file up -d"
fi
